mod support;
use autotune_recovery_contract::{process::*, storage::FileIdentity, *};
fn measured(pid: u32) -> MeasuredProcess {
    MeasuredProcess {
        process: ProcessIdentity {
            pid,
            creation_100ns: pid as u64 * 10,
            binary: [4; 32],
            logon_sid: "S-1-5-5-1-2".into(),
            integrity: 8192,
        },
        user_sid: "S-1-5-21-1".into(),
        image: FileIdentity {
            volume: 7,
            id: [3; 16],
        },
    }
}
fn context() -> ChannelContext {
    ChannelContext {
        version: PROCESS_VERSION,
        session: [1; 32],
        supervisor_role: Role::Launcher,
        supervisor: measured(1),
        child_role: Role::Guardian,
        child: measured(2),
    }
}
#[test]
fn process_handshake_golden_vectors_bind_roles_peers_challenges_lengths_and_macs() {
    let context = context();
    let context_hex: String = context
        .digest()
        .unwrap()
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect();
    assert_eq!(
        context_hex,
        "89e20c6142bace84c13a5e325c1a98b96055a9ba9f29f7dbbe670aebd1d924f8"
    );
    let frames = [
        challenge(&context, Role::Launcher, 1, [5; 32], [0; 32]).unwrap(),
        challenge(&context, Role::Guardian, 1, [6; 32], [5; 32]).unwrap(),
        challenge(&context, Role::Launcher, 2, [5; 32], [6; 32]).unwrap(),
    ];
    for (i, f) in frames.iter().enumerate() {
        let bytes = encode_frame(f, &[9; 32]).unwrap();
        // Independent Python json/hashlib/hmac vectors, not generated by this encoder.
        let expected = [
            "eb6b5473ccc4e4dc478e173ef7e147ff0c17a8455791bfd4513031416b0c4aff",
            "27c668b7b6397088296608688d7d038d6fcf792cf3c10ebc291d0a1382c95a25",
            "bba9c29d1d69df2e68cf3a89251aa0280294c30f92bb8ba2a1edb4e49f32cd9a",
        ];
        assert_eq!(bytes.len(), 660);
        assert_eq!(u32::from_le_bytes(bytes[..4].try_into().unwrap()), 656);
        assert_eq!(
            bytes[bytes.len() - 32..]
                .iter()
                .map(|b| format!("{b:02x}"))
                .collect::<String>(),
            expected[i]
        );
        verify_challenge(
            f,
            &context,
            f.from,
            if i == 1 { [6; 32] } else { [5; 32] },
            if i == 0 {
                [0; 32]
            } else if i == 1 {
                [5; 32]
            } else {
                [6; 32]
            },
        )
        .unwrap();
    }
}
#[test]
fn bootstrap_strict_roundtrip_secret_redaction_and_handle_inventory_rejections() {
    let b = ProcessBootstrap {
        context: context(),
        handles: InheritedHandles {
            bootstrap_map: 100,
            supervisor_query: 104,
            custody: None,
        },
        pipe: format!(r"\\.\pipe\AutoTune-fake-v1-{}", "a".repeat(64)),
        key: [9; 32],
        fixture_root: Some("synthetic:fixture".into()),
        console_test: false,
        profile: FakeProfile {
            device: support::preparation().device,
            runtime: support::runtime(),
            baseline_mw: 247_123,
            minimum_mw: 100_000,
            maximum_mw: 300_000,
            default_mw: Some(215_000),
            behavior: FakeBehavior::Normal,
        },
    };
    b.validate().unwrap();
    let bytes = canonical(&b).unwrap();
    assert_eq!(
        decode::<ProcessBootstrap>(&bytes, BOOTSTRAP_LIMIT).unwrap(),
        b
    );
    assert!(format!("{b:?}").contains("[REDACTED]"));
    assert!(!format!("{b:?}").contains("9, 9"));
    let mut console = b.clone();
    console.console_test = true;
    console.validate().unwrap(); // Guardian stays detached; only its coordinator opts in.
    assert_eq!(
        decode::<ProcessBootstrap>(&canonical(&console).unwrap(), BOOTSTRAP_LIMIT).unwrap(),
        console
    );
    let mut worker = b.clone();
    worker.context.supervisor_role = Role::Guardian;
    worker.context.child_role = Role::Worker;
    worker.fixture_root = None;
    worker.handles.custody = Some(CustodyHandle {
        handle: 108,
        identity: worker.context.child.image,
    });
    worker.validate().unwrap();
    worker.console_test = true;
    assert!(
        worker.validate().is_err(),
        "worker may never request a console"
    );
    let mut bad = b.clone();
    bad.handles.supervisor_query = 100;
    assert!(bad.validate().is_err());
    let mut bad = b.clone();
    bad.context.child.process.creation_100ns += 1;
    assert_ne!(bad.context.digest().unwrap(), b.context.digest().unwrap());
    let mut bad = b.clone();
    bad.context.child.process.logon_sid = "S-1-5-5-wrong".into();
    assert!(bad.validate().is_err());
    let mut bad = b;
    bad.context.child_role = Role::Worker;
    assert!(bad.validate().is_err());
}
